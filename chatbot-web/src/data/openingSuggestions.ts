/** 题库打平后的一维数组：抽题只认它，领域分组不参与。 */
const POOL: readonly string[] = SUGGESTION_GROUPS.flatMap((g) => g.questions)

/** 一次显示几条。空状态是三个 chip 并排最美观，改这个数要顺带看一眼 `.chips` 的换行。 */
export const SUGGESTION_COUNT = 3

/**
 * 「洗牌发牌」用的牌堆，模块级变量。
 *
 * 为什么不用每次 `Math.random()` 抽 3 条：100 条里随机抽 3 条，连着两次撞上一两条是常态，
 * 用户会觉得「怎么又是这个」。发牌保证**一轮内不重复**，100 条全轮完才重新洗。
 *
 * 放在模块级而不是 localStorage：刷新页面就重新洗牌，正好对应「每次打开都换一批」；
 * 存 localStorage 反而会让新用户几天都看到同一批。
 */
let deck: string[] = []

function reshuffle(): void {
  deck = [...POOL]
  // Fisher-Yates：从后往前逐个和前面（含自己）的随机位置交换，每一步都能取到全部排列
  for (let i = deck.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    const tmp = deck[i]!
    deck[i] = deck[j]!
    deck[j] = tmp
  }
}

/**
 * 从牌堆里抽 `count` 条，抽走的不会再出现，直到一轮发完重新洗牌。
 *
 * 用 `while` 而不是「不够就先洗、再 splice」：后者会把牌堆底部剩的 1~2 条直接丢掉，
 * 那几条就会比别的题目出现得更频繁。
 */
export function drawSuggestions(count: number = SUGGESTION_COUNT): string[] {
  const limit = Math.min(count, POOL.length)
  const picked: string[] = []
  while (picked.length < limit) {
    if (deck.length === 0) {
      reshuffle()
    }
    picked.push(deck.pop()!)
  }
  return picked
}